-- kajukatli · hyprland entry point
-- every piece lives in ./modules so a mistake in one file is easy to find.
-- check for errors with:  hyprctl configerrors

local function load(name)
    local ok, err = pcall(require, name)
    if not ok then
        hl.notification.create({ text = "kajukatli: failed to load " .. name .. ": " .. tostring(err), timeout = 10000, icon = "error" })
    end
end

load("modules/vars")
load("modules/gpu")       -- generated by install.sh (igpu/dgpu routing)
load("modules/env")
load("modules/monitors")
load("modules/look")
load("modules/theme")     -- regenerated by kk-theme on every wallpaper change
load("modules/input")
load("modules/binds")
load("modules/rules")
load("modules/autostart")
load("modules/user")      -- yours. never overwritten.
